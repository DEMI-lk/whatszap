#!/usr/bin/env node
/**
 * Per-user Linux installer (no root required).
 *
 *   npm run install:linux        # build + install
 *   node scripts/install-linux.cjs --uninstall
 *
 * Installs:
 *   ~/.local/share/whatszap/                 unpacked app (release/linux-unpacked)
 *   ~/.local/bin/whatszap                    launcher wrapper
 *   ~/.local/share/applications/whatszap.desktop
 *   ~/.local/share/icons/hicolor/512x512/apps/whatszap.png
 *
 * Electron's Chromium sandbox needs the SUID helper (chrome-sandbox) owned by
 * root with mode 4755. A per-user install cannot provide that, so the wrapper
 * launches with --no-sandbox when the helper is not configured (the same
 * fallback scripts/launch.cjs uses in development). Run
 * `sudo chown root:root ... && sudo chmod 4755 ...` on that file to restore
 * full renderer sandboxing.
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.join(__dirname, '..');
const unpacked = path.join(root, 'release', 'linux-unpacked');

const dataHome = process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local', 'share');
const binDir = path.join(os.homedir(), '.local', 'bin');
const installDir = path.join(dataHome, 'whatszap');
const applicationsDir = path.join(dataHome, 'applications');
const iconDir = path.join(dataHome, 'icons', 'hicolor', '512x512', 'apps');

const wrapperPath = path.join(binDir, 'whatszap');
const desktopPath = path.join(applicationsDir, 'whatszap.desktop');
const iconPath = path.join(iconDir, 'whatszap.png');

function uninstall() {
  for (const p of [installDir, wrapperPath, desktopPath, iconPath]) {
    fs.rmSync(p, { recursive: true, force: true });
    console.log(`[install] removed ${p}`);
  }
  refreshDesktopDatabase();
  console.log('\n[install] WhatsZAP uninstalled (profile data in ~/.config/WhatsZAP was kept).');
}

function findExecutable() {
  const entries = fs.readdirSync(unpacked);
  // electron-builder names the binary after package.json "name" (whatszap),
  // but accept the product name too if a future config changes it.
  for (const wanted of ['whatszap', 'WhatsZAP']) {
    if (entries.includes(wanted)) {
      const p = path.join(unpacked, wanted);
      try {
        if (fs.statSync(p).isFile()) return wanted;
      } catch {
        /* keep looking */
      }
    }
  }
  throw new Error(`No app executable found in ${unpacked} (looked for whatszap/WhatsZAP).`);
}

function refreshDesktopDatabase() {
  for (const cmd of [['update-desktop-database', [applicationsDir]], ['gtk-update-icon-cache', ['-q', path.join(dataHome, 'icons', 'hicolor')]]]) {
    try {
      execFileSync(cmd[0], cmd[1], { stdio: 'ignore' });
    } catch {
      /* optional tools — ignore when missing */
    }
  }
}

function install() {
  if (!fs.existsSync(unpacked)) {
    console.error(`[install] ${unpacked} not found.\n[install] Run \`npm run dist:linux:dir\` (or \`npm run install:linux\`) first.`);
    process.exit(1);
  }
  const exe = findExecutable();

  console.log(`[install] copying app to ${installDir}`);
  fs.rmSync(installDir, { recursive: true, force: true });
  fs.mkdirSync(installDir, { recursive: true });
  fs.cpSync(unpacked, installDir, { recursive: true });

  // Launcher wrapper: prefer the real SUID sandbox when it is configured,
  // otherwise fall back to --no-sandbox so the app always starts.
  fs.mkdirSync(binDir, { recursive: true });
  const wrapper = `#!/bin/sh
# WhatsZAP launcher (generated by scripts/install-linux.cjs)
APP_DIR="${installDir}"
BIN="$APP_DIR/${exe}"
SANDBOX="$APP_DIR/chrome-sandbox"
if [ -f "$SANDBOX" ] && [ "$(stat -c '%u:%a' "$SANDBOX" 2>/dev/null)" = "0:4755" ]; then
  exec "$BIN" "$@"
fi
exec "$BIN" --no-sandbox "$@"
`;
  fs.writeFileSync(wrapperPath, wrapper, { mode: 0o755 });

  fs.mkdirSync(applicationsDir, { recursive: true });
  fs.writeFileSync(
    desktopPath,
    `[Desktop Entry]
Type=Application
Name=WhatsZAP
GenericName=WhatsApp Web Client
Comment=WhatsApp Web desktop client with isolated profiles
Exec=${JSON.stringify(wrapperPath)} %U
Icon=whatszap
Terminal=false
Categories=Network;InstantMessaging;
StartupWMClass=whatszap
`,
    { mode: 0o644 },
  );

  fs.mkdirSync(iconDir, { recursive: true });
  fs.copyFileSync(path.join(root, 'assets', 'icon.png'), iconPath);

  refreshDesktopDatabase();

  console.log(`[install] launcher:  ${wrapperPath}`);
  console.log(`[install] desktop:   ${desktopPath}`);
  console.log(`[install] icon:      ${iconPath}`);
  console.log('\n[install] Done. Start WhatsZAP from your app grid, or run: whatszap');
  if (!process.env.PATH.split(':').includes(binDir)) {
    console.log(`[install] Note: ${binDir} is not on PATH in this shell; log out/in or add it.`);
  }
}

if (process.argv.includes('--uninstall')) uninstall();
else install();
